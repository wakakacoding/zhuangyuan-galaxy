export interface MapStat { mapped: number; dropped: number; unknown: number }

/** 查一个 ASSOC code 的映射规则；表外码返回 null（由调用方按 unknown 计数） */
export const mapAssocCode = (code: number): AssocRule | null => rules.get(code) ?? null;

/** 表内规则总数（报告用） */
export const ruleCount = (): number => rules.size;

/** 列出所有已登记码，按族聚合（报告用） */
export const rulesByFamily = (): Map<SemanticFamily, number[]> => {
  const out = new Map<SemanticFamily, number[]>();
  for (const [code, r] of [...rules.entries()].sort((a, b) => a[0] - b[0])) {
    const arr = out.get(r.family) ?? [];
    arr.push(code);
    out.set(r.family, arr);
  }
  return out;
};

export { TEXTUAL_DISCARD };
