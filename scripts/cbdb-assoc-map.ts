import { RELATION_TYPES } from '../src/lib/schema';

export type LocalRelationType = (typeof RELATION_TYPES)[number];

/** 语义族：本站关系语义框架。同乡/共事暂未在 schema 落点（M6 细化候选） */
export type SemanticFamily =
  | '同年' | '师生' | '同乡' | '姻亲' | '共事' | '政敌'
  | '文本交往' | '经济依附' | '司法军事' | '其他';

export interface AssocRule {
  /** 落点型；null = 本站暂无可承载类型 → 丢弃 */
  type: LocalRelationType | null;
  family: SemanticFamily;
  /** 判定依据，随报告输出供人工审查 */
  why: string;
}

const rules = new Map<number, AssocRule>();
const add = (
  codes: number[], type: LocalRelationType | null, family: SemanticFamily, why: string,
): void => {
  for (const c of codes) rules.set(c, { type, family, why });
};

